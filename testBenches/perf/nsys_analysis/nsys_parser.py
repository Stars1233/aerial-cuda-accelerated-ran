"""Parse an Aerial GPU Benchmark nsys-rep into per-channel kernel latency.

Approach (context + static cuPHY kernel map)
--------------------------------------------
Each channel group runs in its own CUDA context (the MPS sub-contexts from the
``*_isolate`` flags, or green contexts). We group kernels by **context**
(``contextId`` for MPS, ``greenContextId`` for green contexts — auto-detected),
then **label each context by its dominant channel** using a static kernel ->
channel map (``_CHANNEL_KERNELS``) derived from the cuPHY source tree.

The map is built from the ``__global__`` kernel definitions under ``cuPHY/src``:
each kernel defined in a **channel-specific** directory (e.g.
``cuphy/channel_eq`` -> PUSCH, ``cuphy/pdcch`` -> PDCCH, ``cuphy/csirs`` ->
CSI-RS, ``cuphy_channels/pusch_rx`` -> PUSCH, …) is listed below. Kernels from
**shared** function dirs (LDPC, CRC, rate-matching, polar, scrambling, …) are
recognized as ``shared`` and attributed to whichever context they run in (the
context resolves the channel; their name alone can't). Kernels that are neither
(test-bench timing / graph / wait kernels) are ``infra`` and excluded.

Each context becomes ONE channel report, labeled by the channel-specific kernels
that dominate its busy time. For the CICD cases that is exactly five reports:
PDSCH, PUSCH, PUCCH, PDCCH, PRACH (PDCCH and CSI-RS share a context by design;
the context is labeled by its dominant channel and the CSI-RS kernels are shown
within it). The pure timing/anchor context is dropped.

Latency only
------------
nsys has no FLOP counters, so this emits latency only (CUPTI kernel durations).
Within a channel, kernels are grouped by name into an array giving both the
aggregate latency (count + mean/min/max/p50/p90/p99) and the separate
per-instance durations (``instances_us``). Per-kernel latency is GPU busy time;
it is not the channel's end-to-end (event-based) latency the dashboard's latency
panel shows.

Classification: include-by-default, blacklist the infra
--------------------------------------------------------
Every kernel is MEANINGFUL and kept unless it matches the infra blacklist
(``_INFRA_PREFIXES``: timing/pacing, graph machinery, generic data movement).
A brand-new cuPHY kernel therefore shows up on the dashboard by default —
the failure mode of an out-of-date map is visible noise, never invisible loss.

The channel a kept kernel is attributed to is resolved by the first match of:

1. exact short name in ``_CHANNEL_KERNELS`` (a trailing version suffix such as
   ``_v3`` / ``V2`` is stripped first, so ``fusedPdcchTxKernelV0/V1/V2/...`` all
   resolve via one ``fusedPdcchTxKernel`` entry);
2. the C++ **namespace** of the demangled name via ``_NAMESPACE2CHANNEL``
   (e.g. ``embedPdcchTx::`` -> PDCCH, ``csirsTf::`` -> CSI-RS) — this is what
   makes future kernels added inside an existing channel namespace work without
   touching this file;
3. cuMAC name patterns (``_MAC_NAME_PREFIXES`` / ``_MAC_NAME_SUBSTRINGS``) ->
   MAC. The cuMAC workload is a TensorRT MLP engine, and TRT/Myelin kernel
   names are engine-build-specific (arch, tactic, hash), so they match by
   pattern rather than exact name. Must run before the infra blacklist, whose
   ``__`` prefix would swallow the Myelin ``__myl_*`` kernels;
4. ``_SHARED_PREFIXES`` (LDPC/CRC/polar/... function-library kernels) ->
   ``(shared)``, attributed to their context's channel;
5. the infra blacklist (``_INFRA_PREFIXES``) -> ``(infra)``, excluded;
6. otherwise ``(unclassified)``: KEPT in its context's kernel list exactly like
   ``(shared)``, and a warning listing the names is printed to stderr as a
   prompt to either add a channel mapping or a blacklist entry. Neither
   ``(shared)`` nor ``(unclassified)`` kernels vote when labeling a context by
   its dominant channel.

Regenerating the static map
---------------------------
``_CHANNEL_KERNELS`` was generated by scanning ``cuPHY/src`` for ``__global__``
definitions and mapping each kernel's defining directory to a channel. If cuPHY
adds/renames channel kernels, re-scan and update the sets below (or extend
``_NAMESPACE2CHANNEL`` — preferred, it covers whole families at once).

Usage
-----
    python3 nsys_parser.py run.nsys-rep -o kernels.json   # needs `nsys` on PATH
    python3 nsys_parser.py run.sqlite   -o kernels.json   # pre-exported sqlite
"""

